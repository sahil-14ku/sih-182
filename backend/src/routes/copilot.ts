import { Router, Request, Response } from 'express';
import { isDatabaseConnected } from '../config/database';
import { Case, Attribution, RiskAssessment } from '../models';
import { DEMO_CASES, getCaseFromMemory } from '../data/demoData';
import { runAttributionEngine } from '../engines/attributionEngine';
import { runRiskEngine } from '../engines/riskEngine';
import { logAudit } from './auditLogs';

const router = Router();

type CopilotQuery =
  | 'WHY_HIGH_RISK'
  | 'WHY_VASP_SELECTED'
  | 'SHORTEST_VASP_PATH'
  | 'TYPOLOGIES_DETECTED'
  | 'SUMMARIZE_INVESTIGATION'
  | 'PREPARE_REPORT_SUMMARY';

const detectQueryType = (query: string): CopilotQuery => {
  const q = query.toLowerCase();
  if (q.includes('risk') || q.includes('high risk')) return 'WHY_HIGH_RISK';
  if (q.includes('vasp') && (q.includes('why') || q.includes('selected') || q.includes('chosen')))
    return 'WHY_VASP_SELECTED';
  if (q.includes('path') || q.includes('shortest') || q.includes('route')) return 'SHORTEST_VASP_PATH';
  if (q.includes('typolog') || q.includes('pattern') || q.includes('detected'))
    return 'TYPOLOGIES_DETECTED';
  if (q.includes('summar') || q.includes('overview')) return 'SUMMARIZE_INVESTIGATION';
  if (q.includes('report')) return 'PREPARE_REPORT_SUMMARY';
  return 'SUMMARIZE_INVESTIGATION';
};

// POST /api/copilot/query
router.post('/query', async (req: Request, res: Response) => {
  try {
    const { caseId, query } = req.body;

    if (!caseId || !query) {
      return res.status(400).json({ success: false, error: 'caseId and query are required' });
    }

    let targetCase: any = null;
    let attribution: any = null;
    let risk: any = null;

    if (isDatabaseConnected()) {
      targetCase = await Case.findOne({ caseId }).lean();
      attribution = await Attribution.findOne({ caseId }).lean();
      risk = await RiskAssessment.findOne({ caseId }).lean();
    }

    if (!targetCase) {
      targetCase = getCaseFromMemory(caseId) || DEMO_CASES.find((c) => c.caseId === caseId);
    }

    if (!targetCase) {
      return res.status(404).json({ success: false, error: 'Case not found' });
    }

    if (!attribution) {
      attribution = runAttributionEngine(caseId);
    }

    if (!risk) {
      risk = runRiskEngine(caseId);
    }

    const topCandidate = attribution.candidates?.[0] || {
      vaspName: targetCase.likelyVasp || 'Unknown VASP',
      confidence: targetCase.vaspConfidence || 90,
      hopDistance: 2,
      vaspPath: [targetCase.suspectWallet],
      evidenceIds: [`EVD-${caseId}-CLU-001`],
      scoreBreakdown: { clusterMatch: 35, transactionProximity: 25, behaviourSimilarity: 15, depositPattern: 10, temporalMetadata: 5 },
      clusterMatchDetails: 'Cluster matches known deposit pattern',
      proximityDetails: 'Close proximity in transaction graph',
      behaviourDetails: 'Rapid forwarding behaviour',
      depositPatternDetails: 'Deterministic deposit structure',
      temporalDetails: 'Consistent active hours',
      disclaimer: 'Investigative intelligence — requires human verification',
    };

    const queryType = detectQueryType(query);
    let answer = '';
    let evidenceIds: string[] = [];
    let confidence = 0;

    switch (queryType) {
      case 'WHY_HIGH_RISK':
        evidenceIds = [`EVD-${caseId}-FRAUD-001`, `EVD-${caseId}-RMV-001`, `EVD-${caseId}-INT-001`];
        confidence = 88;
        answer =
          `Based on structured analysis of case ${caseId}, the suspect wallet is rated **${risk.riskLevel}** with a risk score of **${risk.overallScore}/100** for the following evidence-backed reasons:\n\n` +
          (risk.factors || [])
            .filter((f: any) => f.detected)
            .map(
              (f: any) => `• **${f.name}** (${f.score}/${f.maxScore || 40} pts): ${f.description}`
            )
            .join('\n') +
          `\n\nDetected typologies: ${(risk.typologies || []).map((t: any) => `**${t.name}**`).join(', ') || 'None'}\n\n` +
          `⚠️ This assessment is generated by rule-based analysis. Human investigator verification is required before any legal action.`;
        break;

      case 'WHY_VASP_SELECTED':
        evidenceIds = topCandidate.evidenceIds || [];
        confidence = topCandidate.confidence;
        answer =
          `**${topCandidate.vaspName}** was selected as the most probable VASP endpoint (Rank #1, Confidence: ${topCandidate.confidence}%) based on the following deterministic evidence:\n\n` +
          `• **Cluster Match** (${topCandidate.scoreBreakdown?.clusterMatch || 35}/40): ${topCandidate.clusterMatchDetails}\n` +
          `• **Transaction Proximity** (${topCandidate.scoreBreakdown?.transactionProximity || 25}/30): ${topCandidate.proximityDetails}\n` +
          `• **Behaviour Similarity** (${topCandidate.scoreBreakdown?.behaviourSimilarity || 15}/15): ${topCandidate.behaviourDetails}\n` +
          `• **Deposit Pattern** (${topCandidate.scoreBreakdown?.depositPattern || 10}/10): ${topCandidate.depositPatternDetails}\n` +
          `• **Temporal Metadata** (${topCandidate.scoreBreakdown?.temporalMetadata || 5}/5): ${topCandidate.temporalDetails}\n\n` +
          `⚠️ ${topCandidate.disclaimer || 'Investigative intelligence — requires human verification'}`;
        break;

      case 'SHORTEST_VASP_PATH':
        evidenceIds = [`EVD-${caseId}-PRX-001`, `EVD-${caseId}-CLU-001`];
        confidence = 85;
        const path: string[] = topCandidate.vaspPath || [targetCase.suspectWallet];
        const wallets = targetCase.wallets || [];
        const pathDisplay = path
          .map((addr, i) => {
            const wallet = wallets.find((w: any) => w.address === addr);
            return `${i + 1}. \`${addr.slice(0, 20)}...\` — ${wallet?.label || 'Intermediate'}`;
          })
          .join('\n');
        answer =
          `**Shortest VASP Path** (${topCandidate.hopDistance || 2} hops) to **${topCandidate.vaspName}**:\n\n` +
          pathDisplay +
          '\n\n' +
          `Total traced value: ~$${(targetCase.transactions || []).reduce((s: number, t: any) => s + (t.valueUsd || 0), 0).toLocaleString()} USD\n\n` +
          `⚠️ Path is reconstructed from transaction graph analysis. Synthetic demonstration dataset.`;
        break;

      case 'TYPOLOGIES_DETECTED':
        evidenceIds = (risk.typologies || []).map((_: any, i: number) => `EVD-${caseId}-TYP-00${i + 1}`);
        confidence = 82;
        if (!risk.typologies || risk.typologies.length === 0) {
          answer = `No specific financial crime typologies were detected for case ${caseId} based on current evidence.`;
        } else {
          answer =
            `**${risk.typologies.length} Typology/Typologies Detected** in case ${caseId}:\n\n` +
            risk.typologies
              .map(
                (t: any, i: number) =>
                  `### ${i + 1}. ${t.name} (${t.code})\n` +
                  `Confidence: ${t.confidence}%\n` +
                  `${t.description}\n\n` +
                  `**Indicators:**\n${(t.indicators || []).map((ind: string) => `• ${ind}`).join('\n')}`
              )
              .join('\n\n---\n\n') +
            `\n\n⚠️ Typology detection is rule-based. Confirmation requires financial crime expert review.`;
        }
        break;

      case 'SUMMARIZE_INVESTIGATION':
      default:
        evidenceIds = [`EVD-${caseId}-CLU-001`, `EVD-${caseId}-PRX-001`, `EVD-${caseId}-TMP-001`];
        confidence = 90;
        answer =
          `## Investigation Summary — ${targetCase.title}\n\n` +
          `**Case:** ${targetCase.caseId} | **Type:** ${(targetCase.type || '').replace(/_/g, ' ').toUpperCase()} | **Priority:** ${(targetCase.priority || '').toUpperCase()}\n\n` +
          `**Suspect Wallet:** \`${targetCase.suspectWallet}\` (${(targetCase.blockchain || '').toUpperCase()})\n\n` +
          `**Risk Score:** ${targetCase.riskScore}/100 (${risk.riskLevel})\n\n` +
          `**Most Likely VASP:** ${targetCase.likelyVasp} (${targetCase.vaspConfidence}% confidence)\n\n` +
          `**Fund Flow:** ${(targetCase.transactions || []).length}-hop chain across ${new Set((targetCase.wallets || []).map((w: any) => w.blockchain)).size} blockchain(s)\n\n` +
          `**Detected Typologies:** ${(risk.typologies || []).map((t: any) => t.name).join(', ') || 'None'}\n\n` +
          `**Investigator Notes:** ${targetCase.investigatorNotes}\n\n` +
          `⚠️ All findings are intelligence leads requiring human verification. Synthetic demo case.`;
        break;

      case 'PREPARE_REPORT_SUMMARY':
        evidenceIds = topCandidate.evidenceIds || [];
        confidence = 88;
        answer =
          `## Report Summary — ${targetCase.title}\n\n` +
          `**INTELLIGENCE LEAD — FOR INVESTIGATIVE PURPOSES ONLY**\n\n` +
          `Case ${targetCase.caseId} involves a suspect ${(targetCase.type || '').replace(/_/g, ' ')} scenario on the ` +
          `${(targetCase.blockchain || '').toUpperCase()} blockchain. Automated analysis has traced a ${(targetCase.transactions || []).length}-hop ` +
          `fund flow from suspect wallet \`${(targetCase.suspectWallet || '').slice(0, 20)}...\` to a probable deposit ` +
          `address associated with **${targetCase.likelyVasp}** (${targetCase.vaspConfidence}% attribution confidence).\n\n` +
          `The risk assessment score of **${targetCase.riskScore}/100** (${risk.riskLevel}) is driven by: ` +
          `${(risk.factors || []).filter((f: any) => f.detected).map((f: any) => f.name).join(', ')}.\n\n` +
          `This report is suitable for initiating a MLAT request or FIU referral after human investigator verification.\n\n` +
          `**Citing Evidence IDs:** ${(topCandidate.evidenceIds || []).join(', ')}`;
        break;
    }

    await logAudit({
      action: 'COPILOT_QUERIED',
      caseId,
      userId: 'demo-investigator',
      userRole: 'investigator',
      details: `AI Copilot queried: "${query.slice(0, 50)}..."`,
      resourceType: 'Copilot',
      severity: 'info',
    });

    res.json({
      success: true,
      data: {
        query,
        queryType,
        answer,
        evidenceIds,
        confidence,
        disclaimer:
          '⚠️ AI responses are explanations of pre-computed structured evidence only. AI does not determine attribution or risk scores.',
        timestamp: new Date().toISOString(),
      },
      demoMode: !isDatabaseConnected(),
      storage: isDatabaseConnected() ? 'mongodb' : 'fallback_demo',
    });
  } catch (err) {
    res.status(500).json({ success: false, error: String(err) });
  }
});

export default router;
